#!/usr/bin/env node
// create-artubeplate — scaffold an Artube RGS slot game on @artubeplate/core.
//
//   npm create artubeplate@latest my-game
//   npm create artubeplate@latest my-game -- --math ./their-math --game-server-id 1234
//   node create-artubeplate/index.js my-game --core ./artubeplate-core-0.1.0.tgz   (unpublished core)
//
// Zero dependencies (Node built-ins only). Copies `template/` into the target, substitutes the
// project name, and — with `--math` — drops a provided math folder in place of the sample one:
// an Artube upload set goes straight into `math/`; a Stake Engine publish folder is staged in
// `math-stake/` for `npm run math:from-stake` (the converter ships with @artubeplate/core).

import { readFile, writeFile, mkdir, readdir, rename, copyFile, rm, stat } from 'node:fs/promises';
import { existsSync, realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve, basename } from 'node:path';
import { parseArgs } from 'node:util';
import { createInterface } from 'node:readline/promises';
import { stdin, stdout } from 'node:process';

const here = dirname(fileURLToPath(import.meta.url));
const templateDir = join(here, 'template');

// The @artubeplate/core range the scaffold pins (the template dev-links `workspace:*`).
const CORE_VERSION = '^2.0.0';

const isText = (n) => /\.(ts|tsx|js|jsx|mjs|cjs|json|html?|css|md|txt|ya?ml|svg|env|example)$/i.test(n) || n === '_gitignore' || n === '.gitignore';

const useColor = stdout.isTTY && !process.env.NO_COLOR;
const c = (code) => (s) => (useColor ? `\x1b[${code}m${s}\x1b[0m` : String(s));
const bold = c('1'), dim = c('2'), green = c('32'), cyan = c('36'), red = c('31'), yellow = c('33');

function packageManager() {
  const ua = process.env.npm_config_user_agent || '';
  if (ua.startsWith('pnpm')) return 'pnpm';
  if (ua.startsWith('yarn')) return 'yarn';
  if (ua.startsWith('bun')) return 'bun';
  return 'npm';
}

/**
 * The @artubeplate/core dependency to write: the published range by default, or — for a core
 * that is not on npm yet — a local folder, written as an ABSOLUTE `file:` spec (it installs on this
 * machine only; a tarball is vendored instead, see {@link vendoredCore}). Anything else (a range,
 * a tag) is used as given.
 */
export function coreSpec(input, cwd = process.cwd()) {
  if (!input) return CORE_VERSION;
  const raw = input.startsWith('file:') ? input.slice(5) : input;
  const local = input.startsWith('file:') || /^(\.{1,2}[\\/]|[\\/]|[A-Za-z]:[\\/])/.test(raw) || raw.endsWith('.tgz');
  return local ? `file:${resolve(cwd, raw)}` : input;
}

/**
 * A local @artubeplate/core TARBALL goes into the project (`vendor/<name>.tgz`) and is written as a
 * RELATIVE `file:` spec, so the project installs anywhere — Artube's pipeline (`npm ci`) included.
 * `null` for anything that is not a `.tgz` path.
 */
export function vendoredCore(input, cwd = process.cwd()) {
  if (!input) return null;
  const raw = input.startsWith('file:') ? input.slice(5) : input;
  if (!raw.endsWith('.tgz')) return null;
  const from = resolve(cwd, raw);
  return { from, spec: `file:vendor/${basename(from)}` };
}

/** npm-safe package name from a directory name. */
export function sanitizeName(input) {
  const n = input
    .trim()
    .toLowerCase()
    .replace(/^[._]+/, '')
    .replace(/[^a-z0-9-~]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return n || 'artube-game';
}

/** A readable title from the directory name: `lucky-cats` → `Lucky Cats`. */
export function titleOf(name) {
  return name
    .split(/[-_~]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join(' ');
}

const SKIP = new Set(['node_modules', 'dist', '.vite', 'test-results', '.assetpack']);
// Generated by the asset pipeline from raw-assets/ on the first `npm run dev` / `build`.
const SKIP_PATHS = new Set(['public/assets']);

async function copyDir(src, dest, vars, rel = '') {
  await mkdir(dest, { recursive: true });
  for (const entry of await readdir(src, { withFileTypes: true })) {
    const s = join(src, entry.name);
    const d = join(dest, entry.name);
    const r = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      if (!SKIP.has(entry.name) && !SKIP_PATHS.has(r)) await copyDir(s, d, vars, r);
    } else if (entry.name === 'package.json') {
      const pkg = JSON.parse(await readFile(s, 'utf8'));
      pkg.name = vars.name;
      pkg.version = '0.1.0';
      for (const field of ['dependencies', 'devDependencies']) {
        for (const k of Object.keys(pkg[field] ?? {})) if (String(pkg[field][k]).startsWith('workspace:')) pkg[field][k] = vars.core;
      }
      await writeFile(d, JSON.stringify(pkg, null, 2) + '\n');
    } else if (isText(entry.name)) {
      await writeFile(d, (await readFile(s, 'utf8')).replaceAll('{{name}}', vars.title).replaceAll('{{package}}', vars.name));
    } else {
      await copyFile(s, d);
    }
  }
}

/** What kind of math folder is this? `artube` (has `settings`), `stake` (modes only), or null. */
export async function mathKind(dir) {
  const idx = join(dir, 'index.json');
  if (!existsSync(idx)) return null;
  try {
    const m = JSON.parse(await readFile(idx, 'utf8'));
    if (m && typeof m === 'object' && m.settings && Array.isArray(m.modes)) return 'artube';
    if (m && Array.isArray(m.modes)) return 'stake';
  } catch {
    /* not JSON */
  }
  return null;
}

/** Copy only the files an index.json references (+ index.json) — the set must hold nothing extra. */
async function copyMath(src, dest) {
  const m = JSON.parse(await readFile(join(src, 'index.json'), 'utf8'));
  const files = new Set(['index.json', ...m.modes.flatMap((x) => [x.events, x.weights])]);
  await rm(dest, { recursive: true, force: true });
  await mkdir(dest, { recursive: true });
  const missing = [];
  for (const f of files) {
    if (existsSync(join(src, f))) await copyFile(join(src, f), join(dest, f));
    else missing.push(f);
  }
  return { files: [...files], missing };
}

function printHelp() {
  console.log(`
${bold('create-artubeplate')} — scaffold an Artube RGS slot game on @artubeplate/core

${bold('Usage')}
  npm create artubeplate@latest ${cyan('<dir>')} [-- options]

${bold('Options')}
  --math <dir>            use this math instead of the sample: an Artube upload set
                          (index.json + lookUpTable_* + books_*) or a Stake Engine
                          publish_files folder (converted after install)
  --game-server-id <id>   a fallback for the RGS hub's \`game\` → .env (Artube launch
                          URLs carry it as ?gameId=, which always wins)
  --core <spec>           the @artubeplate/core to depend on (default ${CORE_VERSION}); a
                          packed .tgz is copied into vendor/ (file:vendor/…, installs in
                          Artube's pipeline too); a folder is linked as file:<abs path>
                          (this machine only)
  -y, --yes               no prompts
  -h, --help
`);
}

async function main() {
  const { positionals, values } = parseArgs({
    allowPositionals: true,
    options: {
      yes: { type: 'boolean', short: 'y' },
      help: { type: 'boolean', short: 'h' },
      math: { type: 'string' },
      'game-server-id': { type: 'string' },
      core: { type: 'string' },
    },
  });
  if (values.help) return printHelp();

  let target = positionals[0];
  if (!target && !values.yes) {
    const rl = createInterface({ input: stdin, output: stdout });
    target = (await rl.question(`${bold('Project directory')} ${dim('(artube-game)')}: `)).trim();
    rl.close();
  }
  target = target || 'artube-game';
  const dir = resolve(process.cwd(), target);
  const name = sanitizeName(basename(dir));
  const title = titleOf(name);

  if (existsSync(dir) && (await readdir(dir).catch(() => [])).length > 0) {
    console.error(red(`\n✖ ${target} already exists and is not empty. Choose another directory.\n`));
    process.exit(1);
  }

  let mathSrc = null;
  let kind = null;
  if (values.math) {
    mathSrc = resolve(process.cwd(), values.math);
    if (!existsSync(mathSrc) || !(await stat(mathSrc)).isDirectory()) {
      console.error(red(`\n✖ --math ${values.math}: not a folder.\n`));
      process.exit(1);
    }
    kind = await mathKind(mathSrc);
    if (!kind) {
      console.error(red(`\n✖ --math ${values.math}: no readable index.json — expected an Artube upload set or a Stake publish_files folder.\n`));
      process.exit(1);
    }
  }

  const vendored = vendoredCore(values.core);
  if (vendored && !existsSync(vendored.from)) {
    console.error(red(`\n✖ --core ${values.core}: no such file.\n`));
    process.exit(1);
  }
  const core = vendored ? vendored.spec : coreSpec(values.core);

  console.log(`\n${dim('Scaffolding')} ${bold(title)} ${dim(`(${name}) in`)} ${target}${dim('…')}`);
  await copyDir(templateDir, dir, { name, title, core });
  if (vendored) {
    await mkdir(join(dir, 'vendor'), { recursive: true });
    await copyFile(vendored.from, join(dir, 'vendor', basename(vendored.from)));
  }
  if (existsSync(join(dir, '_gitignore'))) await rename(join(dir, '_gitignore'), join(dir, '.gitignore'));
  if (values['game-server-id']) await writeFile(join(dir, '.env'), `VITE_GAME_SERVER_ID=${values['game-server-id']}\n`);

  let mathNote = '';
  if (mathSrc && kind === 'artube') {
    const { files, missing } = await copyMath(mathSrc, join(dir, 'math'));
    mathNote = `  ${green('✔')} math/ ← ${values.math} (${files.length} files${missing.length ? `, ${yellow(`missing: ${missing.join(', ')}`)}` : ''})`;
  } else if (mathSrc && kind === 'stake') {
    const { files } = await copyMath(mathSrc, join(dir, 'math-stake'));
    mathNote = `  ${yellow('!')} ${values.math} is a Stake Engine folder — staged in math-stake/ (${files.length} files); convert it after install.`;
  }

  const pm = packageManager();
  const run = pm === 'npm' ? 'npm run' : pm;
  const cd = target === '.' ? '' : `  cd ${target}\n`;
  const coreNote = vendored
    ? `  ${green('✔')} @artubeplate/core ← vendor/${basename(vendored.from)} ${dim('(commit it: the pipeline installs from it)')}`
    : core.startsWith('file:/')
      ? `  ${yellow('!')} @artubeplate/core is linked from ${core.slice(5)}: fine here, but Artube's pipeline cannot install it.\n    Run ${cyan('npm pack')} there and scaffold with ${cyan('--core <the .tgz>')} to vendor it.`
      : '';
  const lockNote = pm === 'npm' ? '' : `\n  ${dim('•')} you use ${pm}: run ${cyan('npm install')} once too, so ${cyan('package-lock.json')} exists`;
  console.log(`
${green('✔ Done!')} Your Artube game is ready.
${mathNote ? `\n${mathNote}\n` : ''}${coreNote ? `\n${coreNote}\n` : ''}
${bold('Next steps')}
${cd}  ${pm} install
${kind === 'stake' ? `  ${run} math:from-stake -- math-stake --out math   ${dim('# Stake → Artube (+ a starter client config)')}\n` : ''}  ${run} math:check     ${dim('# the checks Artube Hub runs on upload')}
  ${run} dev            ${dim('# plays on a local mock RGS that draws from math/')}
  ${run} build          ${dim("# dist/ (Artube's pipeline runs the same)")}

${bold('Ship')}
  ${dim('•')} ${cyan('math/')}  → Artube Hub (Upload Math → Start Math Verification); Artube publishes it
  ${dim('•')} ${cyan('code')}   → push to ${cyan('<studio>/<publicGameId>/client')} in Artube's GitLab. Its pipeline is
             Artube's (no .gitlab-ci.yml here): npm ci + npm run build on Node 22 → the CDN.
             develop → DEV, prod → Stage, tag vX.Y.Z on prod → Production
  ${dim('•')} commit ${cyan('package-lock.json')} (the pipeline installs with npm ci)${lockNote}
  ${dim('•')} test from the game card in Artube Hub: PLAY / DEMO, or Play on Localhost → ${run} dev

${dim('Docs: https://github.com/schmooky/artubeplate')}
`);
}

// Imported (by the tests) → only the helpers above; run as the bin (a symlink under
// node_modules/.bin, hence realpath) → scaffold.
const invoked = process.argv[1] ? realpathSync(process.argv[1]) : '';
if (invoked === realpathSync(fileURLToPath(import.meta.url))) {
  main().catch((err) => {
    console.error(red(`\n✖ ${err?.message || err}\n`));
    process.exit(1);
  });
}
